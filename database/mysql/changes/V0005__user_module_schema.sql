-- ---------------------------------------------------------------------------
-- User module schema: users, roles, permissions and their link tables.
--
-- Foreign keys are enforced by the database even though entities keep identifiers only
-- (no JPA relations). Everyday queries are simple; reporting joins live in SQL DAOs.
-- ---------------------------------------------------------------------------

CREATE TABLE USERS (
    ID             BIGINT       NOT NULL AUTO_INCREMENT,
    USERNAME       VARCHAR(100) NOT NULL,
    PASSWORD_HASH  VARCHAR(200) NOT NULL,
    FULL_NAME      VARCHAR(200) NOT NULL,
    MOBILE         VARCHAR(20)  NULL,
    EMAIL          VARCHAR(200) NULL,
    BIRTH_DATE     DATE         NULL,
    STATUS         VARCHAR(20)  NOT NULL,
    LAST_LOGIN_AT  DATETIME(6)  NULL,
    CREATED_DATE   DATETIME(6)  NOT NULL,
    MODIFIED_DATE  DATETIME(6)  NOT NULL,
    CREATED_BY     BIGINT       NOT NULL,
    MODIFIED_BY    BIGINT       NOT NULL,
    VERSION        BIGINT       NOT NULL,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_USERS_USERNAME (USERNAME),
    UNIQUE KEY UK_USERS_MOBILE (MOBILE)
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4
  COLLATE = utf8mb4_unicode_ci;

CREATE TABLE ROLES (
    ID            BIGINT       NOT NULL AUTO_INCREMENT,
    CODE          VARCHAR(50)  NOT NULL,
    TITLE         VARCHAR(100) NOT NULL,
    CREATED_DATE  DATETIME(6)  NOT NULL,
    MODIFIED_DATE DATETIME(6)  NOT NULL,
    CREATED_BY    BIGINT       NOT NULL,
    MODIFIED_BY   BIGINT       NOT NULL,
    VERSION       BIGINT       NOT NULL,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_ROLES_CODE (CODE)
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4
  COLLATE = utf8mb4_unicode_ci;

CREATE TABLE PERMISSIONS (
    ID            BIGINT       NOT NULL AUTO_INCREMENT,
    CODE          VARCHAR(100) NOT NULL,
    TITLE         VARCHAR(150) NOT NULL,
    CREATED_DATE  DATETIME(6)  NOT NULL,
    MODIFIED_DATE DATETIME(6)  NOT NULL,
    CREATED_BY    BIGINT       NOT NULL,
    MODIFIED_BY   BIGINT       NOT NULL,
    VERSION       BIGINT       NOT NULL,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_PERMISSIONS_CODE (CODE)
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4
  COLLATE = utf8mb4_unicode_ci;

CREATE TABLE USER_ROLE (
    ID            BIGINT      NOT NULL AUTO_INCREMENT,
    USER_ID       BIGINT      NOT NULL,
    ROLE_ID       BIGINT      NOT NULL,
    CREATED_DATE  DATETIME(6) NOT NULL,
    MODIFIED_DATE DATETIME(6) NOT NULL,
    CREATED_BY    BIGINT      NOT NULL,
    MODIFIED_BY   BIGINT      NOT NULL,
    VERSION       BIGINT      NOT NULL,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_USER_ROLE (USER_ID, ROLE_ID),
    KEY IX_USER_ROLE_ROLE (ROLE_ID),
    CONSTRAINT FK_USER_ROLE_USER FOREIGN KEY (USER_ID) REFERENCES USERS (ID) ON DELETE CASCADE,
    CONSTRAINT FK_USER_ROLE_ROLE FOREIGN KEY (ROLE_ID) REFERENCES ROLES (ID) ON DELETE RESTRICT
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4
  COLLATE = utf8mb4_unicode_ci;

CREATE TABLE ROLE_PERMISSION (
    ID            BIGINT      NOT NULL AUTO_INCREMENT,
    ROLE_ID       BIGINT      NOT NULL,
    PERMISSION_ID BIGINT      NOT NULL,
    CREATED_DATE  DATETIME(6) NOT NULL,
    MODIFIED_DATE DATETIME(6) NOT NULL,
    CREATED_BY    BIGINT      NOT NULL,
    MODIFIED_BY   BIGINT      NOT NULL,
    VERSION       BIGINT      NOT NULL,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_ROLE_PERMISSION (ROLE_ID, PERMISSION_ID),
    KEY IX_ROLE_PERMISSION_PERMISSION (PERMISSION_ID),
    CONSTRAINT FK_ROLE_PERMISSION_ROLE FOREIGN KEY (ROLE_ID) REFERENCES ROLES (ID) ON DELETE CASCADE,
    CONSTRAINT FK_ROLE_PERMISSION_PERMISSION FOREIGN KEY (PERMISSION_ID) REFERENCES PERMISSIONS (ID) ON DELETE RESTRICT
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4
  COLLATE = utf8mb4_unicode_ci;

-- The refresh token table was created before the user table existed.
ALTER TABLE REFRESH_TOKEN
    ADD CONSTRAINT FK_REFRESH_TOKEN_USER FOREIGN KEY (USER_ID) REFERENCES USERS (ID) ON DELETE CASCADE;

